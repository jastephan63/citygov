def ech_state(u):
    """eCH state of one Datenfeld or Teilfeld — the key export_json stamped on it
    (ech_state, a key of ton_map.ech). ONE classification: the figures count it, the
    dashboard draws it, the dossier words it; nothing is derived here."""
