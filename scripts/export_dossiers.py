def esc(s):
    """A value on its way into the page — as text or inside a quoted attribute
    (& < > " ' are written as entities). Every value from the export passes here."""
    return html.escape(str(s if s is not None else ""), quote=True)


def web_href(url):
    """A link target taken from the data (DVSH, eCH): only an http(s) address becomes
    a link. Anything else — «www.…» without a scheme, javascript:, «<UNKNOWN>» —
    returns "" and the caller prints plain text."""
    url = str(url or "").strip()
    return esc(url) if re.match(r"https?://\S+$", url, re.I) else ""


def page_href(path, fragment=""):
    """A page of this repository as link target (dossier, PDF, dashboard route): the
    path percent-encoded, then escaped for the attribute."""
    return esc(urllib.parse.quote(str(path), safe="/.-_~")
               + ("#" + urllib.parse.quote(str(fragment), safe="/.-_~") if fragment else ""))


def code_name(s):
    """An eCH element or type name on its way into the page. A very long camelCase name
    («applicationForCreditingForeign…», 76 characters) gets break opportunities (<wbr>)
    at its word boundaries, so it cannot push a table wider than the page; the name
    itself is unchanged."""
    s = str(s if s is not None else "")
    if len(s) < 40:
        return esc(s)
    return "<wbr>".join(esc(p) for p in re.split(r"(?<=[a-z0-9])(?=[A-Z])", s))


# ---- the contact line: one wording with the dashboard (kontaktHtml) -----------
# «Kontakt (laut DVSH): Adresse · Tel. +41 52 … · E-Mail …» — address first, then
# telephone, then e-mail, each named; without a contact «nicht hinterlegt». The parts
# are printed as the DVSH stores them — a number or an address is never rewritten;
# telephone and e-mail are links, and only the TARGET of a tel: link is put into the
# international form. Tests and order are the dashboard's (build_dashboard.py,
# kontaktHtml) and the guided forms' (build_flows.py); the words («Kontakt (laut
# DVSH)», «Tel.», «E-Mail», «nicht hinterlegt») are labels.KONTAKT, read by all three.
KONTAKT_LABEL = LABELS.KONTAKT["label"] + ":"
KONTAKT_LEER = LABELS.KONTAKT["leer"]
MAIL_RX = re.compile(r"[^\s@]+@[^\s@]+\.[a-z]{2,}$", re.I)
TEL_RX = re.compile(r"\+?[\d\s()/.-]+$")


def tel_target(p):
    """«052 632 74 66» -> «+41526327466»: what a tel: link dials, in international
    form (a number with the Swiss trunk 0 gets +41; «+41 (0)52 …» loses the (0))."""
    d = re.sub(r"[^\d+]", "", p.replace("(0)", ""))
    if d.startswith("00"):
        return "+" + d[2:]
    if d.startswith("0"):
        return "+41" + d[1:]
    return d


def kontakt_parts(k):
    """The stored contact as [(kind, text)], kind ∈ mail · tel · text, in stored order.
    An entry that holds several parts («a@sh.ch · Strasse 1») is split at « · »."""
    out = []
    for x in k or []:
        for p in str(x or "").split(" · "):
            p = p.strip()
            if not p:
                continue
            if MAIL_RX.match(p):
                out.append(("mail", p))
            elif TEL_RX.match(p) and len(re.findall(r"\d", p)) >= 9:
                out.append(("tel", p))
            else:
                out.append(("text", p))
    return out


def kontakt_html(k):
    """The whole contact line: «<b>Kontakt (laut DVSH):</b> Adresse · Tel. <link> ·
    E-Mail <link>»; a Dienststelle without a contact in the DVSH reads «nicht hinterlegt»."""
    adr, tel, mail = [], [], []
    for kind, p in kontakt_parts(k):
        if kind == "mail":
            # the stored address, HTML-escaped — the same target as the dashboard's and the
            # guided forms' kontaktHtml write (one rule, three renderers)
            mail.append(f'{esc(LABELS.KONTAKT["mail"])} <a href="mailto:{esc(p)}">{esc(p)}</a>')
        elif kind == "tel":
            tel.append(f'{esc(LABELS.KONTAKT["tel"])}\u00a0<a class="nw" href="tel:{esc(tel_target(p))}">{esc(p)}</a>')
        else:
            adr.append(esc(p))
    parts = adr + tel + mail
    return (f"<b>{esc(KONTAKT_LABEL)}</b> "
            + (" · ".join(parts) if parts else f'<span class="muted">{esc(KONTAKT_LEER)}</span>'))


