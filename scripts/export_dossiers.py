# the order of the sub-field chips: settled first, then who acts (Kanton, Databank)
STATE_ORDER = ("element", "standard_ohne_elemente", "standard_entwurf", "kein_standard",
               "zuordnung_falsch", "standard_alt", "element_offen", "ungeprueft")


def state_label(code):
    """Reader's word for an eCH state: labels.DIV; the settled element and the mapping
    the databank corrects (the Handlungsbedarf category «zuordnung») have their own."""
    if code == "element":
        return "eCH-Element"
    if code == "zuordnung_falsch":
        return todo_label("zuordnung")
    return render_label(LAB.get("div") or LABELS.DIV, code)


def own_ech(d):
    """What the Databank mapped to ONE data point — a field without sub-fields —
    as a tone badge (ton_map.ech) plus the standard's status where not in force."""
    e = d.get("ech") or {}
    state = ech_state(d)
    stb = std_badge(e)
    if state == "zuordnung_falsch":
        # an element is assigned, but the label means another piece of data: the
        # databank corrects its own mapping — grey, never shown as settled
        return (st(ton_of("ech", state), f'<span class="mono">{esc(e.get("standard"))} {code_name(e.get("element"))}</span>'
                                         f' · {esc(state_label(state))}') + stb)
    if state == "element":
        return (st(ton_of("ech", state), f'<span class="mono">{esc(e.get("standard"))} {code_name(e.get("element"))}</span>')
                + (f' <span class="mono muted">⟨{code_name(e["datatype"])}⟩</span>' if e.get("datatype") else "") + stb)
    if state in ("standard_entwurf", "standard_alt"):
        # a standard not in force: the mapping cannot be cited — still in the making
        # (the canton decides meanwhile) or no longer in force (the databank replaces
        # it by the successor); the status is the badge's own text
        return st(ton_of("ech", state), f'<span class="mono">{esc(e.get("standard"))}</span> · {esc(e.get("status"))}')
    if state in ("element_offen", "standard_ohne_elemente"):
        # an element is only owed where the databank holds an element catalogue
        # for the standard; without one (process/FHIR standard or XSD not swept)
        # the mapping stays on standard level — labels.DIV words it
        note = "Element offen" if state == "element_offen" else render_label(LABELS.DIV, state)
        return st(ton_of("ech", state), f'<span class="mono">{esc(e.get("standard"))}</span> · {esc(note)}') + stb
    if state == "kein_standard":
        return (st(ton_of("ech", state), "kein eCH-Standard")
                + (f' <span class="b esh">{esc(d["esh"].get("code"))} Entwurf (eSH)</span>' if d.get("esh") else ""))
    return st(ton_of("ech", "ungeprueft"), "nicht geprüft")


def parent_ech(d):
    """The composite field's own mapping as plain muted text — never a tone: the
    unit of the data standard is the sub-field, so the parent's mapping says
    nothing about whether its data points are settled."""
    e = d.get("ech") or {}
    if e.get("element"):
        txt = (f'<span class="mono">{esc(e.get("standard"))} {code_name(e["element"])}</span>'
               + (f' <span class="mono">⟨{code_name(e["datatype"])}⟩</span>' if e.get("datatype") else ""))
    elif e.get("standard"):
        note = (e["status"] if e.get("status") in STD_STATE
                else ("Element offen" if e.get("n_elements") else render_label(LABELS.DIV, "standard_ohne_elemente")))
        txt = f'<span class="mono">{esc(e["standard"])}</span> · {esc(note)}'
    elif d.get("ech_status") == "kein_standard":
        txt = "kein eCH-Standard" + (f' <span class="b esh">{esc(d["esh"].get("code"))} Entwurf (eSH)</span>' if d.get("esh") else "")
    else:
        return ""
    return f'<div class="small muted">Feld als Ganzes: {txt}</div>'


def ech_cell(d):
    subs = [s for s in (d.get("subfields") or []) if isinstance(s, dict)]
    if not subs:
        return own_ech(d)
    # a composite: the tone comes from its sub-fields, one chip per eCH state
    # (ton_map.ech), counted — the same units export_json counts
    by = {}
    for s in subs:
        by.setdefault(ech_state(s), []).append(s)
    chips = []
    for code in sorted(by, key=lambda c: STATE_ORDER.index(c) if c in STATE_ORDER else 99):
        us = by[code]
        lb = state_label(code)
        extra = ""
        if code in ("standard_entwurf", "standard_alt"):
            # which standard, in which status (Sistiert, In Arbeit …)
            seen = []
            for u in us:
                k = f'{(u.get("ech") or {}).get("standard") or ""} {(u.get("ech") or {}).get("status") or ""}'.strip()
                if k not in seen:
                    seen.append(k)
            extra = " · " + ", ".join(seen)
        chips.append(st(ton_of("ech", code), f"{esc(lb)}: {esc(len(us))}{esc(extra)}"))
    # an element-mapped sub-field whose standard is itself not approved keeps
    # the status badge a single field shows (std_badge)
    stat = []
    for u in by.get("element", []):
        b = std_badge(u.get("ech") or {})
        if b and b not in stat:
            stat.append(b)
    stds = []
    for u in by.get("element", []):
        if (u.get("ech") or {}).get("standard") and u["ech"]["standard"] not in stds:
            stds.append(u["ech"]["standard"])
    return (f'<div class="small">{esc(pl(len(subs), "Teilfeld", "Teilfelder"))} — ' + " ".join(chips) + "".join(stat)
            + (f' <span class="muted">({esc(", ".join(stds[:4]))}{"…" if len(stds) > 4 else ""})</span>' if stds else "")
            + "</div>" + parent_ech(d))


