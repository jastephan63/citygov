LAWJUR = {}


def abbrs_of(label):
    """Every candidate short title in a free-text reference: each parenthesised
    abbreviation plus the trailing token ("Art. 3 GesG" -> GesG)."""
    out = [m.group(1) for m in re.finditer(r"\(([^)]{2,24})\)", label or "")]
    parts = (label or "").strip().split()
    if parts:
        out.append(parts[-1])
    return out


def jur_of_ref(x, label, local=None):
    """Bund / Kanton / Ebene offen for one free-text DVSH legal reference.

    The modeller's «recht_bund» list is free text ("Art. 3 GesG", a rechtsbuch
    link, a title) and regularly holds CANTONAL law, so the level is read from
    evidence only: the URL host, an SR/SHR marker, a short title the databank
    knows, or the titled entry in the SAME list that shares the abbreviation.
    Nothing is assumed.
    """
    url = x.get("url") or ""
    if "rechtsbuch.sh.ch" in url or re.search(r"\bSHR\b", label) or re.match(r"(?i)kantonale?s?\b", label):
        return "Kanton"
    if (re.search(r"(^|\.)admin\.ch", url) or re.search(r"\bSR\s?\d", label)
            or re.match(r"(?i)(bundesgesetz|bundesverfassung|bundesbeschluss|bundesratsbeschluss)\b", label)):
        return "Bund"
    if re.match(r"(?i)(interkantonale?s?|konkordat)\b", label):
        return "interkantonal"
    for a in abbrs_of(label):
        j = LABELS.JUR.get(LAWJUR.get(a.lower())) or (local or {}).get(a.lower())
        if j:
            return j
    return "Ebene offen"


def cut(s, n=300):
    """Truncate at the last space before n characters and mark the cut — a legal
    quote never ends mid-word."""
    s = (s or "").strip()
    if len(s) <= n:
        return s
    head = s[:n]
    sp = head.rfind(" ")
    return (head[:sp] if sp > n // 2 else head).rstrip(" ,;·") + " …"


def basis_label(d):
    """The answer to the legal question of one Datenfeld as a status badge. WHICH
    answer it is comes from the export (basis_state, a key of ton_map.basis); this
    function only words it."""
    bs = d.get("basis_state")
    if bs == "artikel" and d.get("legal_basis"):
        b = d["legal_basis"][0]
        nr = b.get("sr_number") or b.get("cantonal_ref") or ""
        lc = b.get("last_checked") or ""
        # the proof level of the citation as the ingest scripts set it: a federal
        # article read from the official Fedlex text ('verified'), or an article
        # read from the official law PDF ('Gesetze-PDF …'). The basis itself is
        # «artikel» (geklärt); an unverified quote still leaves the Databank a
        # check to do, so the badge takes the tone of the proof level
        if lc == "verified":
            prov, lv = "verifiziert (Fedlex)", "verified"
        elif lc.startswith("Gesetze-PDF"):
            prov, lv = ("Quelle SHR-PDF" if b.get("jurisdiction") == "cantonal" else "Quelle Gesetzes-PDF"), "quelle_pdf"
        else:
            prov, lv = "Zitat nicht verifiziert", "unverifiziert"
        return (st(ton_of("verif", lv), f'{esc(b.get("article_no"))} {esc((b.get("law_short") or "").strip())}'
                      f'{(" · " + esc(nr)) if nr else ""}') + f' <span class="small muted">{esc(prov)}</span>')
    if bs == "art5_offen":
        # a besonders schützenswerte Angabe judged «aufgabe»: KDSG Art. 4 Abs. 1
        # lit. b is not enough, Art. 5 Abs. 1 lit. a or b must be named -> OPEN
        return st(ton_of("basis", bs), "aufgabennotwendig — Grundlage nach KDSG Art. 5 Abs. 1 noch nicht benannt")
    if bs == "aufgabe":
        return st(ton_of("basis", bs), f'{esc(render_label(LABELS.BASIS_TYP, bs))} (KDSG Art. 4 Abs. 1 lit. b) — keine explizite Norm')
    if bs == "ohne":
        return st(ton_of("basis", bs), f'{esc(render_label(LABELS.BASIS_TYP, bs))} — weder Norm noch Aufgabenbedarf')
    if bs == "offen":
        return st(ton_of("basis", bs), f'{esc(render_label(LABELS.BASIS_TYP, bs))} — keine explizite Norm')
    return st(ton_of("basis", "zu_ermitteln"), "Rechtsgrundlage zu ermitteln")


